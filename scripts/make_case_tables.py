#!/usr/bin/env python3
"""Backup slides listing every case's settings and commits, from data/records/.

    python3 scripts/collect_records.py && python3 scripts/make_case_tables.py

Writes backup_cases.qmd, which slides.qmd includes in its backup section: one slide per case,
a table of the settings every run shares, then a table per group of runs. This script only lays
out data/records/; scripts/collect_records.py reads the runs' own records and dictionaries into it,
and adds the few facts no record carries (the room and lamp descriptions, the Sozzi lamp's exitance
and absorption) as fixed text. To change a table, re-run the case and re-collect its records.
"""

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECORDS = ROOT / "data" / "records"
ORDER = ("refractive_interface", "sozzi_slide10", "sozzi_prototype", "sozzi_swap", "ray_effects_room")


def cell(text):
    """Escape a cell, keeping `code` spans as <code>."""
    parts = html.escape(str(text)).split("`")
    return "".join(f"<code>{p}</code>" if i % 2 else p for i, p in enumerate(parts))


def table(columns, rows, cls):
    head = "".join(f"<th>{cell(c)}</th>" for c in columns)
    body = "".join("<tr>" + "".join(f"<td>{cell(v)}</td>" for v in r) + "</tr>" for r in rows)
    return f'<table class="{cls}"><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>'


# Text scale per record, so each slide's tables fill it without running into the footer: the
# records differ several-fold in length. Tuned on the rendered deck; if collect_records.py makes a
# record longer or shorter, re-tune its value (a record not listed is drawn at 1).
SCALE = {
    "refractive_interface": 2.0,
    "sozzi_slide10": 1.15,
    "sozzi_prototype": 1.6,
    "sozzi_swap": 1.4,
    "ray_effects_room": 1.15,
}


def slide(record, scale=1.0):
    common = "".join(f"<tr><th>{cell(k)}</th><td>{cell(v)}</td></tr>" for k, v in record["common"])
    parts = [f'<table class="rec-common"><tbody>{common}</tbody></table>']
    for t in record["tables"]:
        parts.append(f'<div class="rec-head">{cell(t["title"])}</div>')
        parts.append(table(t["columns"], t["rows"], "rec-runs"))
    for n in record.get("notes", []):
        parts.append(f'<div class="rec-note">{cell(n)}</div>')
    return (f"## Record: {record['title']} {{.smaller .record}}\n\n```{{=html}}\n"
            + f'<div class="rec-body" style="font-size:{scale:g}em">\n'
            + "\n".join(parts) + "\n</div>\n```\n")


def main():
    slides = ["<!-- Generated by scripts/make_case_tables.py from data/records/. Do not edit. -->\n"]
    for case in ORDER:
        f = RECORDS / f"{case}.json"
        if f.exists():
            slides.append(slide(json.loads(f.read_text()), SCALE.get(case, 1.0)))
    (ROOT / "backup_cases.qmd").write_text("\n".join(slides))
    print(f"wrote backup_cases.qmd ({len(slides) - 1} slides)")


if __name__ == "__main__":
    main()
